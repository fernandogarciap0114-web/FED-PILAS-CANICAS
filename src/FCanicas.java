    public void mostrarPilas() {
        Graphics g = PFondo.getGraphics();
        g.setColor(Color.black);
        g.fillRect(0, 0, PFondo.getWidth(), PFondo.getHeight());

        int piso = PFondo.getHeight();

        g.setColor(new Color(255, 127, 0));
        

        for (int t = 0; t < caja.length; t++) {
             g.fillRect(118 + t * 100, 0, 12, piso);
             

            int x = 100 + t * 100;
            int size = caja[t] .size();

            for (int k = 0; k < caja[t].size(); k++) {
                Image can = caja[t].get(k).getImage();
                int y = piso - (size - k) * 50;
                g.drawImage(can, x, y, null);

            }
        }

    }

